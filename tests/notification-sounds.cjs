// Independent browser sound channel: no DOM, browser or dependencies needed.
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const source=fs.readFileSync(path.join(__dirname,'../web/app.js'),'utf8');
const start=source.indexOf('function renderNotificationSounds(');
const end=source.indexOf('function renderNotifications(',start);
assert(start>=0&&end>start);
const played=[];
const context=vm.createContext({playNotificationSound:count=>played.push(count)});
vm.runInContext(source.slice(start,end),context);
const render=context.renderNotificationSounds;
render({notificationSounds:[{id:1,count:3}],notifications:[]});
assert.deepEqual(played,[],'Do not replay history on initial load');
render({notificationSounds:[{id:1,count:3},{id:2,count:2}],notifications:[]});
assert.deepEqual(played,[2],'Sound does not require a center entry');
render({notificationSounds:[{id:1,count:3},{id:2,count:2}],notifications:[]});
assert.deepEqual(played,[2],'Repeated polls do not replay sounds');
render({notificationSounds:[{id:2,count:2},{id:3,count:3},{id:4,count:1}],notifications:[{id:5,sound:0}]});
assert.deepEqual(played,[2,3],'Process the whole batch despite a later silent center entry');
render({notificationSounds:[{id:1,count:1}],notifications:[]});
assert.deepEqual(played,[2,3],'Reset cursor after server restart, without replay');
render({notificationSounds:[{id:1,count:1},{id:2,count:2}]});
assert.deepEqual(played,[2,3,2]);
delete render.last;
render({notifications:[{id:1,sound:0}]});
render({notifications:[{id:2,sound:2},{id:3,sound:0}]});
assert.deepEqual(played,[2,3,2,2],'Compatible with older server center entries');
console.log('PASS: independent sound, polling batches, no duplicates/history replay, restart and older server fallback.');
